func TestScan(t *testing.T) {
	t.Parallel()
	d, err := Scan("testdata/dist", "example/renovate:test")
	if err != nil {
		t.Fatalf("Scan() err = %v", err)
	}

	want := Data{
		Image:        "example/renovate:test",
		Version:      "44.0.0-test",
		Gated:        []string{"gradleWrapper", "pixi"},
		Managers:     []string{"direct", "dynamic", "empty", "indirect", "nodefault", "plain"},
		ExecManagers: []string{"direct", "indirect"},
		FilePatterns: map[string][]string{
			"direct":   {`/(^|\/)direct\.lock$/`, `/(^|/)Directfile$/`},
			"empty":    {},
			"indirect": {`/(^|/)indirect\.toml$/`},
			"plain":    {`/(^|/)plain\.json$/`},
		},
		DynamicPatterns: []string{"dynamic"},
	}
	if !reflect.DeepEqual(d, want) {
		t.Errorf("Scan() =\n%+v\nwant\n%+v", d, want)
	}
}

func TestScan_Errors(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name    string
		options string
		want    string
	}{
		{"option missing", `const o = [{ name: "allowedCommands" }];`, "allowedUnsafeExecutions not found"},
		{"no allowedValues", `const o = [{ name: "allowedUnsafeExecutions", type: "array" }];`, "has no allowedValues"},
		{"bad escape", `const o = [{ name: "allowedUnsafeExecutions", allowedValues: ["a\x"] }];`, "unsupported escape"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			dist := filepath.Join(t.TempDir(), "dist")
			write(t, filepath.Join(dist, "..", "package.json"), `{"version":"1.0.0"}`)
			write(t, filepath.Join(dist, "config", "options", "index.js"), tt.options)
			_, err := Scan(dist, "img")
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Errorf("Scan() err = %v, want it to contain %q", err, tt.want)
			}
		})
	}
}

func TestRender(t *testing.T) {
	t.Parallel()
	d, err := Scan("testdata/dist", "example/renovate:test")
	if err != nil {
		t.Fatalf("Scan() err = %v", err)
	}
	src, err := Render(&d)
	if err != nil {
		t.Fatalf("Render() err = %v", err)
	}
	for _, line := range []string{
		"// Code generated by renovate-unsafe-gen from example/renovate:test (Renovate 44.0.0-test). DO NOT EDIT.",
		`var gated = []string{"gradleWrapper", "pixi"}`,
		`var dynamicPatterns = []string{"dynamic"}`,
		`"empty":    {},`,
		`"direct":   {"/(^|\\/)direct\\.lock$/", "/(^|/)Directfile$/"},`,
	} {
		if !strings.Contains(string(src), line) {
			t.Errorf("Render() lacks %q:\n%s", line, src)
		}
	}
}

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}
